N_CLONES = 3


def make_clones(plan: StrainPlan, parent_rec, parent_fdh: float, rng: np.random.Generator,
                n: int = N_CLONES) -> list:
    """Engineer `plan` on top of the given parent clone as n independent transformants.
    Native-gene changes go through strain_design (NRA, 0.5-1.5 signal, 2x cap); a heterologous FDH
    gets the same 0.5-1.5 expression signal on its nominal activity. Returns [(StrainRecord, fdh)]."""
    out = []
    for c in range(n):
        name = f"{plan.strain_id}-c{c + 1}"
        if plan.mods:
            rec = engineer(parent_rec, plan.mods, name, rng, root=ROOT)
        else:
            rec = dc.replace(parent_rec, name=name, parent=parent_rec.name,
                             strain=parent_rec.strain.copy(name=name))
        fdh = parent_fdh
        if plan.fdh_nominal:
            fdh = plan.fdh_nominal * float(rng.uniform(0.5, 1.5))
        rec.strain = rec.strain.copy(fdh=fdh)
        out.append((rec, fdh))
    return out


